def fmt(value: float) -> str:
    value = float(value)
    if abs(value) >= 100 or (abs(value) < 1e-3 and value != 0.0):
        return f"{value:.2e}"
    return f"{value:.4g}"


def ci(mean: float, low: float, high: float) -> str:
    return f"{fmt(mean)} [{fmt(low)}, {fmt(high)}]"


